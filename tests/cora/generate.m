% Cross-check reference for polyzonotope: runs the same operations in CORA
% and writes the interval hulls of the results to tests/cora/reference.txt.
%
% Run from the repository root, with CORA (https://github.com/TUMcps/CORA)
% checked out somewhere and its path in CORA_PATH:
%
%   CORA_PATH=/path/to/CORA octave --no-gui --quiet tests/cora/generate.m
%
% MATLAB works too and does not need the shims in tests/cora/octave.

1; % a script file, so the helper functions below are allowed

function put(out, name, A)
  % One line: name, rows, columns, then the entries in column-major order.
  fprintf(out, '%s %d %d', name, size(A, 1), size(A, 2));
  if ~isempty(A)   % fprintf prints the format once even without values
    fprintf(out, ' %.17g', A(:));
  end
  fprintf(out, '\n');
end

function s = support(Z, D)
  % Support function of Z in each column of D, as one row.
  s = zeros(1, size(D, 2));
  for j = 1:size(D, 2)
    s(j) = supportFunc(Z, D(:, j));
  end
end

function hull(out, name, I)
  % One line: name, then the lower and upper bounds.
  put(out, name, [infimum(I), supremum(I)]);
end

cora = getenv('CORA_PATH');
if isempty(cora)
  error('set CORA_PATH to a CORA checkout');
end
addpath(genpath(cora));
if exist('OCTAVE_VERSION', 'builtin')
  addpath(fullfile(pwd, 'tests', 'cora', 'octave'));
end
warning('off', 'all');

out = fopen(fullfile('tests', 'cora', 'reference.txt'), 'w');
fprintf(out, '# Generated by tests/cora/generate.m from CORA; do not edit by hand.\n');
for k = 1:8
  n = 2 + mod(k, 2);          % alternate 2-D and 3-D
  h = 3 + mod(k, 3);          % dependent generators
  q = mod(k, 2);              % independent generators
  p = 2;                      % factors
  v = @(m, salt) sin(k * 7.3 + salt + (1:m) * 1.7);   % deterministic values in [-1, 1]
  c = 2 * v(n, 0.1)';
  G = reshape(v(n * h, 0.2), n, h);
  GI = reshape(0.3 * v(n * q, 0.3), n, q);
  E = reshape(mod(round(4 * abs(v(p * h, 0.4))), 4), p, h);
  E(:, sum(E, 1) == 0) = 1;   % no constant monomials, so both sides compact alike
  M = reshape(v(n * n, 0.5), n, n);
  Q1 = reshape(v(n * n, 0.6), n, n);
  Q2 = reshape(v(n * n, 0.7), n, n);
  order = 1 + mod(k, 3) * 0.5;

  pZ = polyZonotope(c, G, GI, E, (1:p)');
  pZnoGI = polyZonotope(c, G, [], E, (1:p)');
  Z = zonotope(pZ);

  fprintf(out, 'case %d\n', k);
  put(out, 'c', c); put(out, 'G', G); put(out, 'GI', GI); put(out, 'E', E);
  put(out, 'M', M); put(out, 'Q1', Q1); put(out, 'Q2', Q2); put(out, 'order', order);
  hull(out, 'hull', interval(pZ));
  hull(out, 'quad', interval(quadMap(pZnoGI, {Q1, Q2})));
  hull(out, 'split', interval(pZ, 'split'));
  hull(out, 'plus', interval(exactPlus(pZ, M * pZ)));
  D = reshape(v(n * 4, 0.8), n, 4);   % directions for support functions
  put(out, 'D', D);
  Rg = reduce(Z, 'girard', order);
  Rp = reduce(Z, 'pca', 1);
  hull(out, 'girard', interval(Rg));
  hull(out, 'pca', interval(Rp));
  % Hulls cannot tell which generators were boxed; support functions can.
  put(out, 'girard_support', support(Rg, D));
  put(out, 'pca_support', support(Rp, D));
end
fclose(out);
