% Cross-check reference for polyzonotope-reach: runs CORA's linearSys reach
% on a few systems and writes the interval hulls of the reachable sets to
% crates/polyzonotope-reach/tests/cora/reference.txt.
%
% Run from the repository root, with CORA (https://github.com/TUMcps/CORA)
% checked out somewhere and its path in CORA_PATH:
%
%   CORA_PATH=/path/to/CORA octave --no-gui --quiet crates/polyzonotope-reach/tests/cora/generate.m
%
% MATLAB works too and does not need the shims in tests/cora/octave.

1; % a script file, so the helper functions below are allowed

function put(out, name, A)
  % One line: name, rows, columns, then the entries in column-major order.
  fprintf(out, '%s %d %d', name, size(A, 1), size(A, 2));
  if ~isempty(A)   % fprintf prints the format once even without values
    fprintf(out, ' %.17g', A(:));
  end
  fprintf(out, '\n');
end

function hulls(out, name, sets)
  % One line: name, rows (lower bounds, then upper bounds), one column per set.
  H = zeros(2 * dim(sets{1}), numel(sets));
  for k = 1:numel(sets)
    I = interval(sets{k});
    H(:, k) = [infimum(I); supremum(I)];
  end
  put(out, name, H);
end

cora = getenv('CORA_PATH');
if isempty(cora)
  error('set CORA_PATH to a CORA checkout');
end
addpath(genpath(cora));
if exist('OCTAVE_VERSION', 'builtin')
  addpath(fullfile(pwd, 'tests', 'cora', 'octave'));
  addpath(fullfile(pwd, 'crates', 'polyzonotope-reach', 'tests', 'cora', 'octave'));
end
warning('off', 'all');

out = fopen(fullfile('crates', 'polyzonotope-reach', 'tests', 'cora', 'reference.txt'), 'w');
fprintf(out, '# Generated by crates/polyzonotope-reach/tests/cora/generate.m from CORA; do not edit by hand.\n');
for k = 1:4
  n = 2 + mod(k, 2);          % alternate 3-D and 2-D
  m = 1 + mod(k, 2);          % inputs
  v = @(len, salt) sin(k * 7.3 + salt + (1:len) * 1.7);   % deterministic values in [-1, 1]
  % A stable A: a random matrix shifted left by more than its norm.
  A = reshape(v(n * n, 0.1), n, n);
  A = A - (norm(A, 1) + 0.5) * eye(n) + [zeros(n, 1), [eye(n - 1); zeros(1, n - 1)]] * 2;
  B = reshape(v(n * m, 0.2), n, m);
  c = 2 * v(n, 0.3)';
  G = 0.2 * reshape(v(n * n, 0.4), n, n);
  cu = 0.5 * v(m, 0.5)';
  if k == 4
    GU = zeros(m, 0);          % a constant input
  else
    GU = 0.1 * diag(abs(v(m, 0.6)) + 0.5);
  end
  r = 0.05 + 0.025 * mod(k, 3);
  terms = 6 + mod(k, 3);
  steps = 10;

  % One oneStep per step, each from the time-point set of the last, as
  % LinearReach steps. CORA's reach front end does not run under Octave, and
  % its standard algorithm propagates the homogeneous and particular parts
  % separately, which gives other sets. oneStep wants the system in
  % canonical form: B = I, the constant input u = B c_u apart, and the
  % varying input centered at the origin.
  sys = linearSys(A, eye(n));
  Uc = zonotope(zeros(n, 1), B * GU);
  u = B * cu;
  X = zonotope(c, G);
  tp = cell(1, steps); ti = cell(1, steps);
  for s = 1:steps
    [X, ti{s}] = oneStep(sys, X, Uc, u, r, terms);
    tp{s} = X;
  end

  fprintf(out, 'case %d\n', k);
  put(out, 'A', A); put(out, 'B', B); put(out, 'c', c); put(out, 'G', G);
  put(out, 'cu', cu); put(out, 'GU', GU);
  put(out, 'r', r); put(out, 'terms', terms); put(out, 'steps', steps);
  hulls(out, 'time_point', tp);
  hulls(out, 'time_interval', ti);
end
fclose(out);
